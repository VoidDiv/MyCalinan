/* ============================================================
   FILE: data/exploreSeed.ts
   The built-in Explore listings that used to live inside each
   Explore page file, now merged into one file. Every page is
   built with the same small entry() builder (same technique as
   the old exploreSeedMore.ts), so adding a listing is always a
   single call - no more hand-written object literals per page.
   The admin's "Import built-in listings" button copies these into
   Firestore once. After that, Firestore is the single source of
   truth and you manage everything from the admin.
   You can delete this file once you have imported.
   ============================================================ */

import type { ExplorePage, ListingData } from "@/types/listing";

export type SeedListing = ListingData & { id: string };

const STORAGE_BASE = "https://storage.googleapis.com/mycalinan.firebasestorage.app";

/** Some mapsQuery strings were written with literal "+" instead of spaces. */
const plain = (s: string) => s.replace(/\+/g, " ");

/**
 * Builds one entry() function per Explore page. Every page follows the
 * same shape (id, name, category, tag, pin, description, address,
 * mapsQuery, file, lat, lng[, tags]) so adding a listing is always a
 * single call, no matter which page it belongs to.
 */
function makeEntryBuilder(page: ExplorePage, folder: string) {
  const base = `${STORAGE_BASE}/${folder}`;
  return function entry(
    id: string,
    name: string,
    category: string,
    tag: string,
    pin: string,
    description: string,
    address: string,
    mapsQuery: string,
    file: string,
    lat: number,
    lng: number,
    tags: string[] = [category]
  ): SeedListing {
    return {
      id,
      name,
      page,
      category,
      tags,
      tag,
      pin,
      description,
      address,
      image: `${base}/${file}`,
      lat,
      lng,
      mapsQuery: plain(mapsQuery),
      published: true,
    };
  };
}

